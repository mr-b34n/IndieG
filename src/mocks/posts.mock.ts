function findCommentRecursively(list: CommentEntity[], id: string): CommentEntity | null {
    for (const c of list) {
        if (String(c.id) === id) return c;
        const children = Array.isArray(c.children)
            ? (c.children.filter((ch): ch is CommentEntity => typeof ch === "object" && ch !== null))
            : (Array.isArray((c as { replies?: CommentEntity[] }).replies) ? (c as { replies?: CommentEntity[] }).replies! : []);
        if (children.length > 0) {
            const found = findCommentRecursively(children, id);
            if (found) return found;
        }
    }
    return null;
}

export const getMockRepliesByCommentId = (commentId: string | number): CommentEntity[] => {
    const idStr = String(commentId || "");
    for (const postId of Object.keys(MOCK_COMMENTS)) {
        const comments = MOCK_COMMENTS[postId] || [];
        const found = findCommentRecursively(comments, idStr);
        if (found) {
            if (Array.isArray(found.children)) {
                return found.children.filter((ch): ch is CommentEntity => typeof ch === "object" && ch !== null);
            }
            if (Array.isArray((found as { replies?: CommentEntity[] }).replies)) {
                return (found as { replies?: CommentEntity[] }).replies!;
            }
        }
    }
    return [];
};

export const addMockComment = (comment: CommentEntity): void => {
    const postId = String(comment.postId || "post-1");
    if (comment.parentId) {
        const pIdStr = String(comment.parentId);
        for (const pid of Object.keys(MOCK_COMMENTS)) {
            const list = MOCK_COMMENTS[pid] || [];
            const parent = findCommentRecursively(list, pIdStr);
            if (parent) {
                if (!Array.isArray(parent.children)) {
                    parent.children = [];
                }
                parent.children.push(comment);
                parent.repliesCount = (parent.repliesCount || 0) + 1;
                return;
            }
        }
    }

    if (!MOCK_COMMENTS[postId]) {
        MOCK_COMMENTS[postId] = [];
    }
    MOCK_COMMENTS[postId].unshift(comment);
};
